import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const checkout = readFileSync(new URL('../app/api/stripe/checkout/route.ts', import.meta.url), 'utf8')
const webhook = readFileSync(new URL('../app/api/stripe/webhook/route.ts', import.meta.url), 'utf8')
const migration = readFileSync(new URL('../supabase/migrations/20261024150000_stripe_webhook_idempotency.sql', import.meta.url), 'utf8')
const account = readFileSync(new URL('../app/account/page.tsx', import.meta.url), 'utf8')
const cookies = readFileSync(new URL('../components/cookie-consent.tsx', import.meta.url), 'utf8')
const styles = readFileSync(new URL('../app/globals.css', import.meta.url), 'utf8')
const legal = readFileSync(new URL('../app/legal/page.tsx', import.meta.url), 'utf8')
const conditions = readFileSync(new URL('../app/condiciones/page.tsx', import.meta.url), 'utf8')
const withdrawal = readFileSync(new URL('../app/desistimiento/page.tsx', import.meta.url), 'utf8')

test('checkout fails closed and requires terms, tax and explicit idempotency', () => {
  assert.match(checkout, /CHECKOUT_ENABLED !== 'true'/)
  assert.match(checkout, /STRIPE_AUTOMATIC_TAX_ENABLED !== 'true'/)
  assert.match(checkout, /STRIPE_ADAPTIVE_PRICING_ENABLED !== 'true'/)
  assert.match(checkout, /adaptive_pricing: \{ enabled: true \}/)
  assert.match(checkout, /payload\.acceptedTerms !== true/)
  assert.match(checkout, /payload\.termsVersion !== TERMS_VERSION/)
  assert.match(checkout, /payload\.acceptedEarlyStart !== true/)
  assert.match(checkout, /payload\.earlyStartConsentVersion !== EARLY_START_CONSENT_VERSION/)
  assert.match(checkout, /early_start_consent_at: consentedAt/)
  assert.match(checkout, /request\.headers\.get\('idempotency-key'\)/)
  assert.match(checkout, /automatic_tax: \{ enabled: true \}/)
  assert.match(checkout, /idempotencyKey:/)
  assert.match(account, /checked=\{acceptedTerms\}/)
  assert.match(account, /Idempotency-Key/)
  assert.match(account, /sessionStorage/)
  assert.match(account, /acceptedEarlyStart/)
  assert.match(account, /earlyStartConsentVersion/)
  assert.match(account, /href="\/condiciones"/)
  assert.match(conditions, /14 días naturales/)
  assert.match(conditions, /BORRADOR/)
  assert.match(withdrawal, /Solicitud de inicio anticipado/)
  assert.match(withdrawal, /14 días naturales/)
})

test('cookie rejection and acceptance are equally styled and no third-party font loads before consent', () => {
  assert.match(cookies, /choose\('essential'\)/)
  assert.match(cookies, /choose\('all'\)/)
  assert.match(cookies, /className="button button-quiet"/)
  assert.doesNotMatch(styles, /fonts\.googleapis\.com/)
  assert.doesNotMatch(legal, /X3091974S/)
  assert.doesNotMatch(legal, /Calle Mundir I 5 3A/)
  assert.match(legal, /Zaragoza, Aragón, España 50001/)
})

test('webhook persists and deduplicates Stripe event IDs', () => {
  assert.match(webhook, /stripe_webhook_events/)
  assert.match(webhook, /event\.livemode !== \(stripeMode === 'live'\)/)
  assert.match(webhook, /MAX_WEBHOOK_BODY_BYTES/)
  assert.match(webhook, /checkout\.sessions\.listLineItems/)
  assert.match(webhook, /session\.payment_status === 'paid'/)
  assert.match(webhook, /event_id: event\.id/)
  assert.match(webhook, /status: 'processed'/)
  assert.match(webhook, /status: 'failed'/)
  assert.match(webhook, /stripe_invoices/)
  assert.match(webhook, /invoices\.retrieve\(eventInvoice\.id\)/)
  assert.match(webhook, /latest_invoice_created_at\.lt/)
  assert.match(migration, /event_id text primary key/)
  assert.match(migration, /enable row level security/)
  assert.match(migration, /revoke all on table public\.stripe_webhook_events from public, anon, authenticated/)
  const invoiceMigration = readFileSync(new URL('../supabase/migrations/20261025100000_stripe_invoice_ledger.sql', import.meta.url), 'utf8')
  assert.match(invoiceMigration, /stripe_invoice_id text primary key/)
  assert.match(invoiceMigration, /latest_invoice_created_at bigint/)
  assert.match(invoiceMigration, /revoke all on table public\.stripe_invoices from public, anon, authenticated/)
})
